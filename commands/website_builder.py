"""Generate a small website and preview it locally.

Goes in: commands/website_builder.py   (new file)

     .env
     GEMINI_API_KEY=sk-...

The content brain writes three files -- index.html, style.css, script.js --
into a site folder under Documents/Jarvis/Sites/<name>. A tiny http.server
thread then serves that folder on 127.0.0.1 so the preview opens in the
user's browser at a clean URL.

WHY THE SERVER LIFETIME IS A FIRST-CLASS CONCERN
------------------------------------------------
This is the exact defect the Brahma reference registers (#21, Medium): the
preview server leaked on EVERY successful build because terminate() only ran on
the failure branch. The fix here is structural, not a one-line patch:

  - Only one preview may exist at a time. Starting a new build stops the
    previous server before anything else happens, so old ports never pile up.
  - The server thread is registered with atexit, so it dies when Jarvis does
    instead of holding the port open forever.
  - The address is always 127.0.0.1 -- a local preview, not a network
    broadcast. Binding 0.0.0.0 would hand every device on the LAN a keyhole
    into a folder full of machine-generated content.

`stop_preview()` is public so a future "stop the preview server" command can
call it directly; for now every new build cleans up the old one.
"""

import atexit
import functools
import threading
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler
from pathlib import Path

from commands import genbrain
from commands import paths

_PREVIEW_HOST = "127.0.0.1"
_PREVIEW_PORT = 8765

# One preview at a time, guarded by a lock because builds can come from
# different thread contexts (executor runs actions on its own thread).
_state_lock = threading.Lock()
_server = None          # the running ThreadingHTTPServer, or None


def build_website(prompt="", target=None):
    """Prompt -> a static site + a live local preview. Returns spoken text."""
    prompt = (prompt or "").strip()
    if not prompt:
        return "I didn't catch what the website should be about."

    stop_preview()  # never leave the previous server holding the port

    try:
        files = genbrain.structured(_SHAPE, prompt, max_tokens=8192)
        html = str(files.get("index.html") or files.get("html") or "").strip()
        css = str(files.get("style.css") or files.get("css") or "").strip()
        js = str(files.get("script.js") or files.get("js") or "").strip()
        title = str(files.get("title") or "Website").strip()
        if not html:
            raise RuntimeError("the model didn't return any page content")
    except Exception as e:
        msg = "Couldn't build the website: {}".format(e)
        print(msg)
        return msg

    # Site directory: Documents/Jarvis/Sites/<slug>, created fresh each build.
    name = _slug(title or "site") or "site"
    site_dir = Path(paths.known_folders()["documents"]) / "Jarvis" / "Sites" / _next_site(
        name)
    try:
        paths.check(site_dir, "write")
        site_dir.mkdir(parents=True, exist_ok=True)
        (site_dir / "index.html").write_text(
            "<!-- generated by Jarvis -->\n{}".format(html), encoding="utf-8")
        (site_dir / "style.css").write_text(css or "/* empty */", encoding="utf-8")
        (site_dir / "script.js").write_text(js or "/* empty */", encoding="utf-8")
    except Exception as e:
        msg = "Couldn't write the site files: {}".format(e)
        print(msg)
        return msg

    started, url = _preview(site_dir)
    if not started:
        return "Couldn't start the preview server for the site."

    try:
        import webbrowser
        webbrowser.open(url)
    except Exception:
        pass

    out = "Built {} in {} and opened a preview at {}.".format(
        site_dir.name, paths.display(site_dir.parent), url)
    print(out)
    return out


# --- The model contract ----------------------------------------------------

_SHAPE = (
    "a JSON object with exactly these keys: title (string), index.html "
    "(string, a complete single-page HTML document with a linked style.css "
    "and script.js), style.css (string, plain CSS), script.js (string, plain "
    "JavaScript). Keep every file COMPACT -- a clean, small page. No external "
    "dependencies, no inline event handlers, no frameworks, no lorem ipsum."
)


def _slug(text):
    safe = "".join(ch if ch.isalnum() or ch == " " else "" for ch in text.lower())
    return "-".join(part for part in safe.split() if part)[:30]


def _next_site(name):
    candidate = name
    n = 2
    base = Path(paths.known_folders()["documents"]) / "Jarvis" / "Sites"
    while base.joinpath(candidate).exists():
        candidate = "{}-{}".format(name, n)
        n += 1
    return candidate


# --- Preview server --------------------------------------------------------

class _Handler(SimpleHTTPRequestHandler):
    """Static handler rooted at the site directory, quiet except on error."""

    def log_message(self, fmt, *args):  # keep the console calm
        pass


def _preview(directory):
    """(started, url). Takes over any existing server via stop_preview()."""
    global _server
    with _state_lock:
        if _server is not None:
            return False, ""

        handler = functools.partial(_Handler, directory=str(directory))
        try:
            server = ThreadingHTTPServer((_PREVIEW_HOST, _PREVIEW_PORT), handler)
        except OSError as e:
            msg = "Couldn't bind the preview port {}: {}".format(_PREVIEW_PORT, e)
            print(msg)
            return False, msg
        server.daemon_threads = True

        def serve():
            try:
                server.serve_forever()
            except Exception:
                pass

        thread = threading.Thread(target=serve, name="jarvis-web-preview", daemon=True)
        thread.start()

        _server = server
        atexit.register(_shutdown_preview)

        url = "http://{}:{}/index.html".format(_PREVIEW_HOST, _PREVIEW_PORT)
        return True, url


def _shutdown_preview():
    global _server
    with _state_lock:
        server = _server
        _server = None
    if server is not None:
        try:
            server.shutdown()
        except Exception:
            pass
        try:
            server.server_close()
        except Exception:
            pass


def stop_preview():
    """Public: stop the running preview (and its thread). Safe to call always."""
    with _state_lock:
        server = _server
    if server is None:
        return False
    _shutdown_preview()
    return True


def stop_preview_voice():
    """Spoken wrapper for the "stop the preview server" command.

    Returns spoken text, so executor can hand it straight to the reply path.
    Deliberately no failure word: stopping a server that isn't running is not
    a failure, and main.py would otherwise spend a model round trip on a
    correction for a no-op.
    """
    if stop_preview():
        return "Stopped the preview server."
    return "There's no preview server running to stop."


if __name__ == "__main__":
    # python -m commands.website_builder  "a tiny landing page for a coffee shop"
    import sys

    probe = " ".join(sys.argv[1:]) or "a minimalist landing page for a small coffee shop"
    print(build_website(probe, "__demo__"))
    if "--stop" in sys.argv:
        stop_preview()
        print("preview stopped")